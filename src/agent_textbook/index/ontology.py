def sections_of(subject: str) -> tuple:
    """该科目录里认可的板块名；未登记的学科返回空（不强猜）。"""
    return SECTIONS.get(subject or "", ())


def slots_of(subject: str) -> dict:
    """该科本体槽位说明（粒度 / 已有层 / 待挖）。"""
    return SLOTS.get(subject or "", {"粒度": "", "层": [], "待挖": []})


def subjects() -> list:
    return sorted(SECTIONS)
