# 年级排序用
GRADE_ORDER = ["一年级", "二年级", "三年级", "四年级", "五年级", "六年级"]
TERM_ORDER = ["上册", "下册"]


def key_of(grade: str, term: str) -> tuple:
    """册次排序键（grade/term 为空的排最后）。"""
    try:
        g = GRADE_ORDER.index(grade)
    except ValueError:
        g = 99
    try:
        t = TERM_ORDER.index(term)
    except ValueError:
        t = 99
    return (g, t)


def math_domain(title: str) -> str:
    """数学单元标题 → 四大领域的 key。"""
    t = (title or "").strip()
    for d in MATH_DOMAINS:
        for k in d["kw"]:
            if k in t:
                return d["key"]
    return "num"


def math_literacy(title: str, points=None) -> list:
    """数学单元 → 主要练的核心素养表现（最多 2 个）。"""
    text = (title or "") + " " + " ".join(points or [])
    hits = []
    for name, kws in MATH_LITERACY:
        for k in kws:
            if k in text:
                hits.append(name)
                break
    seen, out = set(), []
    for h in hits:
        if h not in seen:
            seen.add(h)
            out.append(h)
    return out[:2] or ["运算能力"]


def en_theme(topic: str) -> str:
    """英语单元话题 → 三大主题范畴。"""
    t = (topic or "").lower()
    for name, kws in EN_THEMES:
        for k in kws:
            if k in t:
                return name
    return "人与自我"
